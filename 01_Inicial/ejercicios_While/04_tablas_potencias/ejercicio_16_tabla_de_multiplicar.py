# Pedile al usuario un número y mostrá su tabla de multiplicar del 1 al 10.

n = int(input("Ingresá un número: "))
contador = 1

while  10 >= contador:
    resultado = n * contador
    print(f"{n} x {contador} = {resultado}")
    contador += 1
#--------------------------------------------
print("-" * 30)
